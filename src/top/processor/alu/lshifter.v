module lshifter(A, shift, O);
   input [31:0] A;
   input [4:0]  shift;

   output reg [31:0] O;

   always @ (A, shift)
     begin
        case(shift)
          0 : O <= A[31:0];
          1 : O <= {A[30:0],{1{1'b0}}};
          2 : O <= {A[29:0],{2{1'b0}}};
          3 : O <= {A[28:0],{3{1'b0}}};
          4 : O <= {A[27:0],{4{1'b0}}};
          5 : O <= {A[26:0],{5{1'b0}}};
          6 : O <= {A[25:0],{6{1'b0}}};
          7 : O <= {A[24:0],{7{1'b0}}};
          8 : O <= {A[23:0],{8{1'b0}}};
          9 : O <= {A[22:0],{9{1'b0}}};
          10 : O <= {A[21:0],{10{1'b0}}};
          11: O <= {A[20:0],{11{1'b0}}};
          12 : O <= {A[19:0],{12{1'b0}}};
          13 : O <= {A[18:0],{13{1'b0}}};
          14 : O <= {A[17:0],{14{1'b0}}};
          15 : O <= {A[16:0],{15{1'b0}}};
          16 : O <= {A[15:0],{16{1'b0}}};
          17 : O <= {A[14:0],{17{1'b0}}};
          18 : O <= {A[13:0],{18{1'b0}}};
          19 : O <= {A[12:0],{19{1'b0}}};
          20 : O <= {A[11:0],{20{1'b0}}};
          21 : O <= {A[10:0],{21{1'b0}}};
          22 : O <= {A[9:0],{22{1'b0}}};
