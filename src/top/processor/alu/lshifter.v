          24 : O <= {A[7:0],{24{1'b0}}};
          25 : O <= {A[6:0],{25{1'b0}}};
          26 : O <= {A[5:0],{26{1'b0}}};
          27 : O <= {A[4:0],{27{1'b0}}};
          28 : O <= {A[3:0],{28{1'b0}}};
          29 : O <= {A[2:0],{29{1'b0}}};
          30 : O <= {A[1:0],{30{1'b0}}};
          31 : O <= {A[0:0],{31{1'b0}}};
          default: O <= A[31:0];
        endcase
     end
endmodule
   

                
   
