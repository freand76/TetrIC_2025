module dvi_pattern
  (
   input wire        clk,
   input logic       key_i,
   output wire       tmds_clk_n,
   output wire       tmds_clk_p,
   output wire [2:0] tmds_d_n,
   output wire [2:0] tmds_d_p,
   output wire       div_led
   );

   wire              key;
   assign key = !key_i;
   wire              clk_pixel, clk_pixel_x5, pll_lock, reset;
   logic [2:0]       tmds;
   logic             tmds_clock;

   reg               sys_resetn = 0;
   reg [3:0]         reset_cnt = 15;      // reset for 15 cycles
   always @(posedge clk) begin
      reset_cnt <= reset_cnt == 0 ? 0 : reset_cnt - 1;
      if (reset_cnt == 0)
        sys_resetn <= key;
   end
   assign reset = ~sys_resetn;

   PLL480 pll_dvi (
                   .clkin(clk),
                   .clkout(clk_pixel_x5),
                   .lock(pll_lock)
                   );


   CLKDIV #(.DIV_MODE("5")) clk_div (
                                     .CLKOUT(clk_pixel),
                                     .HCLKIN(clk_pixel_x5),
                                     .RESETN(pll_lock)
                                     );


   reg [23:0] counter;
   always @(posedge clk_pixel)
     counter<=counter+1'b1;

   assign div_led = counter[23];

   localparam BIT_WIDTH = 10;
   localparam BIT_HEIGHT = 10;
   localparam START_X = 0;
   localparam START_Y = 0;
   localparam int NUM_CHANNELS = 3;
   logic          hsync;
   logic          vsync;

   logic [BIT_WIDTH-1:0] cx = START_X;
   logic [BIT_HEIGHT-1:0] cy = START_Y;


   localparam real        VIDEO_RATE = 25.2E6;

   localparam [BIT_WIDTH-1:0] FRAME_WIDTH = 800;
   localparam [BIT_HEIGHT-1:0] FRAME_HEIGHT = 525;
   localparam [BIT_WIDTH-1:0]  SCREEN_WIDTH = 640;
   localparam [BIT_HEIGHT-1:0] SCREEN_HEIGHT = 480;
   localparam [BIT_WIDTH-1:0]  HSYNC_PULSE_START = 16;
   localparam [BIT_WIDTH-1:0]  HSYNC_PULSE_SIZE = 96;
   localparam [BIT_HEIGHT-1:0] VSYNC_PULSE_START = 10;
   localparam [BIT_HEIGHT-1:0] VSYNC_PULSE_SIZE = 2;
   localparam                  INVERT = 1;

   always_comb begin
      hsync <= INVERT ^ (cx >= SCREEN_WIDTH + HSYNC_PULSE_START && cx < SCREEN_WIDTH + HSYNC_PULSE_START + HSYNC_PULSE_SIZE);
      // vsync pulses should begin and end at the start of hsync, so special
      // handling is required for the lines on which vsync starts and ends
      if (cy == SCREEN_HEIGHT + VSYNC_PULSE_START)
        vsync <= INVERT ^ (cx >= SCREEN_WIDTH + HSYNC_PULSE_START);
      else if (cy == SCREEN_HEIGHT + VSYNC_PULSE_START + VSYNC_PULSE_SIZE)
        vsync <= INVERT ^ (cx < SCREEN_WIDTH + HSYNC_PULSE_START);
      else
        vsync <= INVERT ^ (cy >= SCREEN_HEIGHT + VSYNC_PULSE_START && cy < SCREEN_HEIGHT + VSYNC_PULSE_START + VSYNC_PULSE_SIZE);
   end


   localparam BIT_FCNT = 9;
   logic [BIT_FCNT-1:0] frame_cnt = 0;
   logic [BIT_FCNT-1:0] moving_bar = 0;
   logic [BIT_FCNT-1:0] moving_bar2 = 0;

   // Wrap-around pixel position counters indicating the pixel to be generated by the user in THIS clock and sent out in the NEXT clock.
   always_ff @(posedge clk_pixel)
     begin
        if (reset)
          begin
             cx <= BIT_WIDTH'(START_X);
             cy <= BIT_HEIGHT'(START_Y);
             frame_cnt <= 0;
             moving_bar <= 0;
             moving_bar2 <= 0;
          end
        else
          begin
             cx <= cx == FRAME_WIDTH-1'b1 ? BIT_WIDTH'(0) : cx + 1'b1;
             cy <= cx == FRAME_WIDTH-1'b1 ? cy == FRAME_HEIGHT-1'b1 ? BIT_HEIGHT'(0) : cy + 1'b1 : cy;
             frame_cnt <= (cx == FRAME_WIDTH-1'b1) ? (cy == FRAME_HEIGHT-1'b1) ? frame_cnt + 1'b1
                          : frame_cnt : frame_cnt;
             moving_bar <= (cx == FRAME_WIDTH-1'b1) ? frame_cnt : moving_bar;
             moving_bar2 <= (cx == FRAME_WIDTH-1'b1) ? ~frame_cnt : moving_bar2;
          end
     end



   // See Section 5.2
   logic video_data_period = 0;
   always_ff @(posedge clk_pixel)
     begin
        if (reset)
          video_data_period <= 0;
        else
          video_data_period <= cx < SCREEN_WIDTH && cy < SCREEN_HEIGHT;
     end

   logic [2:0] mode = 3'd1;
   logic [23:0] video_data = 24'd0;
   logic [5:0]  control_data = 6'd0;
   logic [11:0] data_island_data = 12'd0;

   logic [7:0]  ybs = 0;

   always_comb begin
      ybs = ({8{~frame_cnt[8]}}^frame_cnt[7:0]) + cy[7:0];
   end

   always_ff @(posedge clk_pixel)
     begin
        if (reset)
          begin
             mode <= 3'd0;
             video_data <= 24'd0;
             control_data <= 6'd0;
          end
        else
          begin
             mode <= video_data_period ? 3'd1 : 3'd0;
             // FANCY RGB DATA
//             video_data <= (cx < 256) ? {cx[7:0], 8'h00, 8'h00} : (cx < 512) ? {8'h00, cx[7:0] , 8'h00} : {8'h00, 8'h00, cx[7:0]};
             video_data <= (cy < 320) ? {8'(~frame_cnt[7:0]+cx[9:2]-{2'b00,cy[8:2]}), 8'(frame_cnt[6]^frame_cnt + cy >> 1), 8'(moving_bar[8]^moving_bar[7:0]+(cx<<1)|(frame_cnt+cy<<1))} : (cy < 480) ? {8'(moving_bar[8:1]+cx[8:1]+ybs), 8'({8{frame_cnt[8]}}^frame_cnt[7:0]), 8'(moving_bar2[8:1] -cx[8:1] +ybs)} : 24'h000000;

             control_data <= {4'b0000, {vsync, hsync}}; // ctrl3, ctrl2, ctrl1, ctrl0, vsync, hsync
          end
     end


   // All logic below relates to the production and output of the 10-bit TMDS code.
   logic [9:0] tmds_internal [NUM_CHANNELS-1:0] /* verilator public_flat */ ;
   genvar      i;
   generate
      // TMDS code production.
      for (i = 0; i < NUM_CHANNELS; i++)
        begin: tmds_gen
           tmds_channel #(.CN(i)) tmds_channel (
                                                .clk_pixel(clk_pixel),
                                                .video_data(video_data[i*8+7:i*8]),
                                                .data_island_data(0),
                                                .control_data(control_data[i*2+1:i*2]),
                                                .mode(mode),
                                                .tmds(tmds_internal[i])
                                                );
        end
   endgenerate


   OSER10 gwSer0(
                 .Q( tmds[ 0 ] ),
                 .D0( tmds_internal[ 0 ][ 0 ] ),
                 .D1( tmds_internal[ 0 ][ 1 ] ),
                 .D2( tmds_internal[ 0 ][ 2 ] ),
                 .D3( tmds_internal[ 0 ][ 3 ] ),
                 .D4( tmds_internal[ 0 ][ 4 ] ),
                 .D5( tmds_internal[ 0 ][ 5 ] ),
                 .D6( tmds_internal[ 0 ][ 6 ] ),
                 .D7( tmds_internal[ 0 ][ 7 ] ),
                 .D8( tmds_internal[ 0 ][ 8 ] ),
                 .D9( tmds_internal[ 0 ][ 9 ] ),
                 .PCLK( clk_pixel ),
                 .FCLK( clk_pixel_x5 ),
                 .RESET( reset ) );

   OSER10 gwSer1(
                 .Q( tmds[ 1 ] ),
                 .D0( tmds_internal[ 1 ][ 0 ] ),
                 .D1( tmds_internal[ 1 ][ 1 ] ),
                 .D2( tmds_internal[ 1 ][ 2 ] ),
                 .D3( tmds_internal[ 1 ][ 3 ] ),
                 .D4( tmds_internal[ 1 ][ 4 ] ),
                 .D5( tmds_internal[ 1 ][ 5 ] ),
                 .D6( tmds_internal[ 1 ][ 6 ] ),
                 .D7( tmds_internal[ 1 ][ 7 ] ),
                 .D8( tmds_internal[ 1 ][ 8 ] ),
                 .D9( tmds_internal[ 1 ][ 9 ] ),
                 .PCLK( clk_pixel ),
                 .FCLK( clk_pixel_x5 ),
                 .RESET( reset ) );

   OSER10 gwSer2(
                 .Q( tmds[ 2 ] ),
                 .D0( tmds_internal[ 2 ][ 0 ] ),
                 .D1( tmds_internal[ 2 ][ 1 ] ),
                 .D2( tmds_internal[ 2 ][ 2 ] ),
                 .D3( tmds_internal[ 2 ][ 3 ] ),
                 .D4( tmds_internal[ 2 ][ 4 ] ),
                 .D5( tmds_internal[ 2 ][ 5 ] ),
                 .D6( tmds_internal[ 2 ][ 6 ] ),
                 .D7( tmds_internal[ 2 ][ 7 ] ),
                 .D8( tmds_internal[ 2 ][ 8 ] ),
                 .D9( tmds_internal[ 2 ][ 9 ] ),
                 .PCLK( clk_pixel ),
                 .FCLK( clk_pixel_x5 ),
                 .RESET( reset ) );

   assign tmds_clock = clk_pixel;

   TLVDS_OBUF tmds_bufds [3:0] (.I({clk_pixel, tmds}),
                                .O({tmds_clk_p, tmds_d_p}),
                                .OB({tmds_clk_n, tmds_d_n}));
endmodule
